#' Net revenue difference-in-means test for randomized experiments
#'
#' @description
#'
#' `net_revenue_test()` analyzes net revenue in a randomized experiment
#' without ever counting order rows as customers. Given a customer cohort
#' (treatment assignment and exposure time), a table of paid orders, a table
#' of (possibly partial) refunds, one common cutoff time, and a fixed
#' observation window, it builds exactly one net-revenue value per *mature*
#' customer and feeds those values through `infer`'s native
#' difference-in-means, permutation, and p-value machinery.
#'
#' A customer is **mature** when their entire observation window is observable
#' at the cutoff, i.e. `exposure + window <= cutoff`. Only mature customers
#' enter the test. Mature customers with no qualifying orders are retained
#' with a net revenue of zero, so the comparison is customer-level rather than
#' an analysis of purchasers only. Immature customers are returned separately
#' and never analyzed.
#'
#' For each mature customer, only paid orders in the half-open window
#' `[exposure, exposure + window)` are counted. Net revenue subtracts the
#' refunds recorded on or before `cutoff` that belong to those counted orders.
#' Refunds are first aggregated to the order level, so several partial refunds
#' on one order can never multiply the order's contribution. All monetary
#' inputs are whole numbers of cents.
#'
#' The point estimate is the difference in mean net revenue, treatment minus
#' control. The permutation distribution is generated by permuting the group
#' label across *customers*, which preserves both group sizes; orders are never
#' permuted and purchasers are never analyzed on their own. The reported
#' p-value is two-sided.
#'
#' @param customers A data frame with one row per customer. Must contain the
#'   customer key, the assigned group, and the exposure time.
#' @param orders A data frame with one row per paid order. Must contain the
#'   order key, the customer key, the order time, and the paid amount.
#' @param refunds A data frame with one row per refund, or `NULL` when there are
#'   no refunds. Must contain the refund key, the order key, the refund time,
#'   and the refund amount. Refunds recorded after `cutoff` are ignored when
#'   computing net revenue, but every refund, regardless of timestamp, must
#'   reference an existing order.
#' @param cutoff A single time: the common as-of time at which order and refund
#'   data are considered complete.
#' @param window The fixed observation window, as a `difftime` or (for `Date`
#'   and `POSIXct` times) a positive number of days. It is applied relative to
#'   each customer's exposure.
#' @param exposure,group,customer_id Column names in `customers` giving the
#'   exposure time, the assigned group, and the customer key.
#' @param order_id,order_time,order_amount Column names in `orders` giving the
#'   order key, the order time, and the paid amount (whole cents).
#' @param refund_id,refund_order_id,refund_time,refund_amount Column names in
#'   `refunds` giving the refund key, the refunded order key, the refund time,
#'   and the refund amount (whole cents).
#' @param treatment,control Optional strings naming the treatment and control
#'   levels of `group`. If only one is supplied, the other is inferred from the
#'   two observed levels. If neither is supplied, `group` must be a factor and
#'   its level order is used (the first level is treatment). The estimate is
#'   always treatment minus control.
#' @param reps A positive whole number: the number of permutation replicates.
#' @param seed Optional single number used to seed the permutation step. The
#'   rest of the computation is deterministic.
#'
#' @return A list of class `net_revenue_test` with elements:
#'
#' \itemize{
#'   \item `estimate`: observed difference in mean net revenue (cents),
#'     treatment minus control.
#'   \item `null_distribution`: a tibble with columns `replicate` and `stat`
#'     (cents), the permutation distribution from [generate()] and
#'     [calculate()].
#'   \item `p_value`: the two-sided permutation p-value from [get_p_value()].
#'   \item `customers`: one row per mature customer, with the counted order
#'     count, gross revenue, refunds, and net revenue (all in cents).
#'   \item `immature_customers`: one row per customer whose window extends past
#'     `cutoff`; these are excluded from the test.
#'   \item `orders`: the order-level attribution detail, including whether each
#'     order was counted and its net contribution.
#'   \item `groups`: the treatment and control labels and the number of mature
#'     customers in each.
#'   \item `reps`, `cutoff`, `window`: the settings used.
#' }
#'
#' @examples
#' customers <- data.frame(
#'   customer_id = c("c1", "c2", "c3", "c4", "c5"),
#'   group = factor(
#'     c("treatment", "treatment", "control", "control", "treatment"),
#'     levels = c("treatment", "control")
#'   ),
#'   exposure = as.Date(c(
#'     "2024-01-01", "2024-01-02", "2024-01-01", "2024-01-03", "2024-01-20"
#'   ))
#' )
#'
#' orders <- data.frame(
#'   order_id = c("o1", "o2", "o3", "o4"),
#'   customer_id = c("c1", "c1", "c3", "c2"),
#'   order_time = as.Date(c(
#'     "2024-01-02", "2024-01-03", "2024-01-02", "2024-01-02"
#'   )),
#'   order_amount = c(5000, 2500, 4000, 1000)
#' )
#'
#' refunds <- data.frame(
#'   refund_id = c("r1", "r2"),
#'   order_id = c("o1", "o1"),
#'   refund_time = as.Date(c("2024-01-04", "2024-01-05")),
#'   refund_amount = c(1000, 500)
#' )
#'
#' net_revenue_test(
#'   customers, orders, refunds,
#'   cutoff = as.Date("2024-01-31"),
#'   window = 14,
#'   reps = 100,
#'   seed = 1
#' )
#'
#' @seealso [calculate()], [generate()], [get_p_value()]
#' @family wrapper functions
#' @export
net_revenue_test <- function(
  customers,
  orders,
  refunds = NULL,
  cutoff,
  window,
  exposure = "exposure",
  group = "group",
  customer_id = "customer_id",
  order_id = "order_id",
  order_time = "order_time",
  order_amount = "order_amount",
  refund_id = "refund_id",
  refund_order_id = "order_id",
  refund_time = "refund_time",
  refund_amount = "refund_amount",
  treatment = NULL,
  control = NULL,
  reps = 1000,
  seed = NULL
) {
  nr_check_data_frame(customers, "customers")
  nr_check_data_frame(orders, "orders")
  if (!is.null(refunds)) {
    nr_check_data_frame(refunds, "refunds")
  }
  nr_check_reps(reps)
  nr_check_seed(seed)

  # Customers ---------------------------------------------------------------
  group_col <- nr_column(customers, group, "group", "customers")
  cust <- tibble::tibble(
    customer_id = nr_ids(
      nr_column(customers, customer_id, "customer_id", "customers"),
      customer_id, "customers"
    ),
    group = nr_group_values(group_col, group, "customers"),
    exposure = nr_time(
      nr_column(customers, exposure, "exposure", "customers"),
      exposure, "customers"
    )
  )
  time_cls <- nr_time_class(cust$exposure)

  cutoff <- nr_single_time(cutoff, "cutoff", time_cls)
  window <- nr_window(window, time_cls)

  groups <- sort(unique(cust$group))
  if (length(groups) != 2L) {
    nr_abort(c(
      "`{group}` in `customers` must contain exactly two groups, but \\
       {length(groups)} were found.",
      "i" = "Found: {paste(groups, collapse = ', ')}.",
      "i" = "Filter `customers` to the two experiment arms before calling \\
             {.fun net_revenue_test}."
    ))
  }
  arms <- nr_resolve_arms(
    group_col, groups, treatment, control, group_name = group
  )

  window_end <- cust$exposure + window
  mature <- !is.na(window_end) & window_end <= cutoff

  # Orders ------------------------------------------------------------------
  ord <- tibble::tibble(
    order_id = nr_ids(
      nr_column(orders, order_id, "order_id", "orders"),
      order_id, "orders"
    ),
    customer_id = nr_group_values(
      nr_column(orders, customer_id, "customer_id", "orders"),
      customer_id, "orders"
    ),
    order_time = nr_time(
      nr_column(orders, order_time, "order_time", "orders"),
      order_time, "orders"
    ),
    amount = nr_money(
      nr_column(orders, order_amount, "order_amount", "orders"),
      order_amount, "orders"
    )
  )
  nr_check_time_class(ord$order_time, time_cls, order_time, "orders")

  # Refunds -----------------------------------------------------------------
  ref <- nr_refund_table(
    refunds,
    refund_id, refund_order_id, refund_time, refund_amount,
    empty_time = cust$exposure[0]
  )
  if (nrow(ref) > 0L) {
    nr_check_time_class(ref$refund_time, time_cls, refund_time, "refunds")
  }

  # Referential integrity is a property of the refund ledger itself, so it is
  # checked across every refund regardless of when it was recorded.
  if (nrow(ref) > 0L) {
    bad_refunds <- setdiff(unique(ref$order_id), ord$order_id)
    if (length(bad_refunds) > 0L) {
      examples <- paste(utils::head(bad_refunds, 5), collapse = ", ")
      nr_abort(c(
        "{length(bad_refunds)} refund{?s} point{?s/} to order{?s} that \\
         {?does/do} not exist in `orders`.",
        "i" = "Dangling refund order ID{?s}: {examples}.",
        "i" = "Every refund must belong to a paid order."
      ))
    }
  }

  # As-of-cutoff refund ledger. Refunds recorded after the cutoff are ignored
  # when computing net revenue.
  ref <- ref[ref$refund_time <= cutoff, , drop = FALSE]

  order_index <- match(ref$order_id, ord$order_id)
  refund_asof <- nr_sum_by(ref$amount, order_index, nrow(ord))

  over <- which(refund_asof > ord$amount)
  if (length(over) > 0L) {
    examples <- paste(
      utils::head(ord$order_id[over], 5), collapse = ", "
    )
    nr_abort(c(
      "{length(over)} order{?s} {?has/have} cumulative refunds exceeding \\
       the paid amount.",
      "i" = "Offending order ID{?s}: {examples}.",
      "i" = "Refund amounts are whole cents and may not exceed the order's \\
             paid amount."
    ))
  }

  # Attribution -------------------------------------------------------------
  cust_index <- match(ord$customer_id, cust$customer_id)
  known <- !is.na(cust_index)

  exposure_at_order <- rep(cust$exposure[NA_integer_], nrow(ord))
  exposure_at_order[known] <- cust$exposure[cust_index[known]]
  mature_at_order <- rep(NA, nrow(ord))
  mature_at_order[known] <- mature[cust_index[known]]

  in_window <- rep(FALSE, nrow(ord))
  in_window[known] <-
    ord$order_time[known] >= exposure_at_order[known] &
    ord$order_time[known] < (exposure_at_order[known] + window)
  in_window[is.na(in_window)] <- FALSE

  counted <- in_window & !is.na(mature_at_order) & mature_at_order
  counted[is.na(counted)] <- FALSE

  net_order <- rep(0, nrow(ord))
  net_order[counted] <- ord$amount[counted] - refund_asof[counted]

  n_counted <- nr_sum_by(
    rep(1, sum(counted)), cust_index[counted], nrow(cust)
  )
  gross <- nr_sum_by(ord$amount[counted], cust_index[counted], nrow(cust))
  refund_counted <- nr_sum_by(
    refund_asof[counted], cust_index[counted], nrow(cust)
  )
  net_customer <- gross - refund_counted

  # Analysis rows: one per mature customer, zeros included -------------------
  analysis <- which(mature)
  if (length(analysis) == 0L) {
    nr_abort("No customers are mature at the supplied `cutoff` and `window`.")
  }

  net_mature <- net_customer[analysis]
  group_mature <- cust$group[analysis]

  n_treatment <- sum(group_mature == arms$treatment)
  n_control <- sum(group_mature == arms$control)

  if (n_treatment == 0L || n_control == 0L) {
    missing_arm <- if (n_treatment == 0L) arms$treatment else arms$control
    nr_abort(
      "No mature customers were found in the {.val {missing_arm}} group; \\
       the difference in means is undefined."
    )
  }

  # Native infer pipeline ----------------------------------------------------
  observed_obj <- nr_infer_object(
    net_mature, group_mature, arms$treatment, arms$control,
    hypothesized = FALSE
  )
  null_obj <- nr_infer_object(
    net_mature, group_mature, arms$treatment, arms$control,
    hypothesized = TRUE
  )

  observed <- calculate(
    observed_obj,
    stat = "diff in means",
    order = c(arms$treatment, arms$control)
  )
  estimate <- observed[["stat"]][[1]]

  group_sym <- rlang::sym("group")
  permute_and_calculate <- function() {
    rlang::inject(
      null_obj |>
        generate(
          reps = reps,
          type = "permute",
          variables = !!group_sym
        ) |>
        calculate(
          stat = "diff in means",
          order = c(arms$treatment, arms$control)
        )
    )
  }

  # With `seed = NULL`, honor the caller's global RNG state rather than
  # resetting it.
  null_dist <- if (is.null(seed)) {
    permute_and_calculate()
  } else {
    withr::with_seed(seed, permute_and_calculate())
  }

  p_value <- get_p_value(
    null_dist,
    observed,
    direction = "two-sided"
  )[["p_value"]][[1]]

  # Tidy output --------------------------------------------------------------
  customers_out <- tibble::tibble(
    customer_id = cust$customer_id[analysis],
    group = cust$group[analysis],
    exposure = cust$exposure[analysis],
    window_end = window_end[analysis],
    n_orders = as.integer(n_counted[analysis]),
    gross_cents = gross[analysis],
    refund_cents = refund_counted[analysis],
    net_revenue_cents = net_mature
  )

  immature <- which(!mature)
  immature_out <- tibble::tibble(
    customer_id = cust$customer_id[immature],
    group = cust$group[immature],
    exposure = cust$exposure[immature],
    window_end = window_end[immature],
    n_orders = as.integer(n_counted[immature]),
    gross_cents = gross[immature],
    refund_cents = refund_counted[immature],
    net_revenue_cents = net_customer[immature]
  )

  status <- rep("counted", nrow(ord))
  status[!known] <- "unknown_customer"
  status[known & !mature_at_order] <- "immature_customer"
  status[known & mature_at_order & !in_window] <- "outside_window"

  orders_out <- tibble::tibble(
    order_id = ord$order_id,
    customer_id = ord$customer_id,
    order_time = ord$order_time,
    order_amount_cents = ord$amount,
    customer_mature = mature_at_order,
    counted = counted,
    refund_cents = refund_asof,
    net_cents = net_order,
    attribution = status
  )

  n_unknown <- sum(!known)
  if (n_unknown > 0L) {
    cli::cli_inform(
      "Ignored {n_unknown} order{?s} whose customer is not in `customers`."
    )
  }

  structure(
    list(
      estimate = estimate,
      null_distribution = null_dist,
      p_value = p_value,
      customers = customers_out,
      immature_customers = immature_out,
      orders = orders_out,
      groups = list(
        treatment = arms$treatment,
        control = arms$control,
        n_treatment = n_treatment,
        n_control = n_control
      ),
      reps = as.integer(reps),
      cutoff = cutoff,
      window = window
    ),
    class = "net_revenue_test"
  )
}

#' @rdname net_revenue_test
#' @param x A `net_revenue_test` result.
#' @param ... Unused.
#' @export
print.net_revenue_test <- function(x, ...) {
  cat("Net revenue difference-in-means test\n")
  cat(
    "  Groups: treatment = ", x$groups$treatment,
    ", control = ", x$groups$control, "\n",
    sep = ""
  )
  cat(
    "  Mature customers: ", nrow(x$customers),
    " (treatment ", x$groups$n_treatment,
    ", control ", x$groups$n_control, ")\n",
    sep = ""
  )
  cat(
    "  Immature customers (excluded): ",
    nrow(x$immature_customers), "\n",
    sep = ""
  )
  cat(
    "  Observed mean difference: ",
    format(x$estimate, trim = TRUE), " cents (treatment - control)\n",
    sep = ""
  )
  cat("  Permutation reps: ", x$reps, "\n", sep = "")
  cat(
    "  Two-sided p-value: ",
    format.pval(x$p_value, digits = 4), "\n",
    sep = ""
  )
  invisible(x)
}

nr_check_reps <- function(reps, call = rlang::caller_env()) {
  if (
    !is.numeric(reps) ||
      length(reps) != 1L ||
      !is.finite(reps) ||
      reps < 1 ||
      reps != trunc(reps)
  ) {
    nr_abort("`reps` must be a single positive whole number.", call = call)
  }

  invisible(reps)
}

nr_check_seed <- function(seed, call = rlang::caller_env()) {
  if (is.null(seed)) {
    return(invisible(seed))
  }

  if (!is.numeric(seed) || length(seed) != 1L || !is.finite(seed)) {
    nr_abort("`seed` must be `NULL` or a single finite number.", call = call)
  }

  invisible(seed)
}

nr_check_time_class <- function(x, cls, arg, what, call = rlang::caller_env()) {
  x_cls <- nr_time_class(x)

  if (!identical(x_cls, cls)) {
    nr_abort(
      "`{arg}` in `{what}` must use the same time type as `exposure` \\
       ({cls}), not {x_cls}.",
      call = call
    )
  }

  invisible(x)
}

nr_resolve_arms <- function(
  group_col,
  groups,
  treatment,
  control,
  group_name = "group",
  call = rlang::caller_env()
) {
  if (!is.null(treatment)) {
    treatment <- as.character(treatment)
    if (length(treatment) != 1L || !treatment %in% groups) {
      nr_abort(
        "`treatment` must be one of the groups in `{group_name}`: \\
         {paste(groups, collapse = ', ')}.",
        call = call
      )
    }
  }

  if (!is.null(control)) {
    control <- as.character(control)
    if (length(control) != 1L || !control %in% groups) {
      nr_abort(
        "`control` must be one of the groups in `{group_name}`: \\
         {paste(groups, collapse = ', ')}.",
        call = call
      )
    }
  }

  if (is.null(treatment) && is.null(control)) {
    if (!is.factor(group_col)) {
      nr_abort(c(
        "Supply `treatment` and/or `control` when `{group_name}` is not a \\
         factor.",
        "i" = "The treatment and control labels must be named explicitly so \\
               the estimate is treatment minus control."
      ), call = call)
    }

    present <- levels(group_col)[levels(group_col) %in% groups]
    treatment <- present[1]
    control <- present[2]
  } else if (is.null(treatment)) {
    treatment <- setdiff(groups, control)
  } else if (is.null(control)) {
    control <- setdiff(groups, treatment)
  }

  if (identical(treatment, control)) {
    nr_abort(
      "`treatment` and `control` must name different groups.",
      call = call
    )
  }

  # The control label must be the only remaining level.
  if (!identical(control, setdiff(groups, treatment))) {
    nr_abort(
      "`treatment` and `control` must be the only two groups in \\
       `{group_name}`.",
      call = call
    )
  }

  list(treatment = treatment, control = control)
}

nr_refund_table <- function(
  refunds,
  refund_id,
  refund_order_id,
  refund_time,
  refund_amount,
  empty_time
) {
  if (is.null(refunds)) {
    return(tibble::tibble(
      refund_id = character(),
      order_id = character(),
      refund_time = empty_time,
      amount = numeric()
    ))
  }

  out <- tibble::tibble(
    refund_id = nr_ids(
      nr_column(refunds, refund_id, "refund_id", "refunds"),
      refund_id, "refunds"
    ),
    order_id = nr_group_values(
      nr_column(refunds, refund_order_id, "refund_order_id", "refunds"),
      refund_order_id, "refunds"
    ),
    refund_time = nr_time(
      nr_column(refunds, refund_time, "refund_time", "refunds"),
      refund_time, "refunds"
    ),
    amount = nr_money(
      nr_column(refunds, refund_amount, "refund_amount", "refunds"),
      refund_amount, "refunds"
    )
  )

  out
}
